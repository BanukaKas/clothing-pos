/**
 * MINT FASHION POS — Customer Release Packaging Script
 * Generates the Windows NSIS customer installer and archives previous versions.
 */

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const pkgJsonPath = path.join(rootDir, 'package.json');
const pkg = JSON.parse(fs.readFileSync(pkgJsonPath, 'utf8'));

const version = pkg.version || '1.1.0';
const customerReleaseDir = path.join(rootDir, 'customer-release');
const archiveDir = path.join(customerReleaseDir, 'archive');
const targetInstallerName = 'MINT-FASHION-POS-Setup.exe';
const targetInstallerPath = path.join(customerReleaseDir, targetInstallerName);
const releaseNotesPath = path.join(customerReleaseDir, 'RELEASE-NOTES.txt');

console.log('====================================================');
console.log(` MINT FASHION POS v${version} — Release Packaging`);
console.log('====================================================\n');

try {
  // 1. Ensure output and archive directories exist
  if (!fs.existsSync(customerReleaseDir)) {
    fs.mkdirSync(customerReleaseDir, { recursive: true });
  }
  if (!fs.existsSync(archiveDir)) {
    fs.mkdirSync(archiveDir, { recursive: true });
  }

  // 2. Archive previous installer if it exists
  if (fs.existsSync(targetInstallerPath)) {
    const stats = fs.statSync(targetInstallerPath);
    if (stats.size > 0) {
      const dateStr = new Date().toISOString().slice(0, 10);
      const archiveName = `MINT-FASHION-POS-Setup-v${version}-${dateStr}.exe`;
      const archivePath = path.join(archiveDir, archiveName);
      console.log(`[Archive] Preserving previous installer -> ${archiveName}`);
      fs.copyFileSync(targetInstallerPath, archivePath);
    }
  }

  // 3. Compile Frontend & Backend
  console.log('\n[1/3] Building production bundles...');
  execSync('node scripts/build.js', { cwd: rootDir, stdio: 'inherit' });

  // 4. Run electron-builder
  console.log('\n[2/3] Building Windows x64 NSIS Installer with electron-builder...');
  execSync('npx electron-builder --win --x64', { cwd: rootDir, stdio: 'inherit' });

  // 5. Locate generated installer in dist-package
  const outputDir = path.join(rootDir, 'dist-package');
  if (!fs.existsSync(outputDir)) {
    throw new Error(`Build output directory not found: ${outputDir}`);
  }

  const files = fs.readdirSync(outputDir);
  const exeFiles = files.filter(f => f.endsWith('.exe') && !f.includes('blockmap'));

  if (exeFiles.length === 0) {
    throw new Error('No .exe installer was generated by electron-builder in dist-package/');
  }

  // Prefer file matching product name or largest exe
  const builtExeName = exeFiles.sort((a, b) => {
    const statA = fs.statSync(path.join(outputDir, a)).size;
    const statB = fs.statSync(path.join(outputDir, b)).size;
    return statB - statA;
  })[0];

  const builtExePath = path.join(outputDir, builtExeName);
  const builtStats = fs.statSync(builtExePath);

  if (builtStats.size === 0) {
    throw new Error(`Generated installer ${builtExeName} is 0 bytes! Packaging failed.`);
  }

  console.log(`\n✓ Found generated installer: ${builtExeName} (${(builtStats.size / (1024 * 1024)).toFixed(2)} MB)`);

  // 6. Copy to customer-release/MINT-FASHION-POS-Setup.exe atomically
  console.log(`[3/3] Deploying verified installer to ${targetInstallerPath}...`);
  fs.copyFileSync(builtExePath, targetInstallerPath);

  // 7. Generate RELEASE-NOTES.txt
  const buildDate = new Date().toISOString().replace('T', ' ').slice(0, 19);
  const releaseNotesContent = `======================================================================
MINT FASHION POS — WINDOWS DESKTOP RELEASE NOTES
======================================================================
Application Name   : MINT FASHION POS
Version            : ${version}
Build Date         : ${buildDate}
Target Platform    : Windows 10 / 11 (64-bit x64)
Database Engine    : SQLite 3 (WebAssembly, 100% Offline)
Installer File     : ${targetInstallerName}
File Size          : ${(builtStats.size / (1024 * 1024)).toFixed(2)} MB

NEW FEATURES & ENHANCEMENTS IN THIS RELEASE:
----------------------------------------------------------------------
1. COMPLETE BARCODE SYSTEM:
   - Automatic unique barcode generation for every new product and variant.
   - Dual support for Code 128 (alphanumeric) and EAN-13 (with Modulo-10 check digit).
   - Real-time duplicate barcode detection across products and variants.
   - Manual barcode editing with inline validation.
   - Controlled barcode regeneration with explicit confirmation dialogs.
   - Permanent SQLite persistence in products and product_variants tables.

2. NEW BARCODE MANAGEMENT STUDIO:
   - Dedicated frontend page for viewing all product and variant barcodes.
   - Multi-criteria filtering by Category, Garment Size, Color, and Barcode Status.
   - Batch selection for multi-product barcode printing.
   - Real-time SVG barcode rendering and inspection.
   - CSV export of all garment barcodes and stock quantities.

3. THERMAL BARCODE LABEL PRINTING:
   - Support for 40x30mm, 50x25mm, 60x40mm and user-defined custom dimensions.
   - Scannable vector barcode graphics (generated via JsBarcode).
   - Toggleable label fields: Store Name, Product Title, Variant (Size/Color),
     SKU, Selling Price, Barcode Graphic, and Human-Readable Digits.
   - Print quantity control per item and bulk quantity multiplier.
   - 100% offline thermal printing.

4. SAFE DATABASE MIGRATIONS & CUSTOMER DATA PROTECTION:
   - Database permanently stored in %APPDATA%/mint-fashion-pos/database/mint-fashion.db.
   - Automatic pre-migration backup before applying schema changes.
   - Incremental migration 002 for variant barcodes and index optimization.
   - Zero-data-loss upgrades: new installers preserve all customer inventory, sales,
     customers, settings, and users.
   - deleteAppDataOnUninstall is disabled to prevent accidental data deletion.

5. POS SCANNER INTEGRATION:
   - Scans both base garment barcodes and variant-specific barcodes.
   - Direct addition of scanned size and color combinations to the active cart.

INSTALLATION INSTRUCTIONS:
----------------------------------------------------------------------
1. Double-click "MINT-FASHION-POS-Setup.exe".
2. Follow the setup wizard to complete the installation.
3. Launch "MINT FASHION POS" from the desktop or Start Menu.
4. Default Administrator login:
   Username: admin
   Password: admin123

UPGRADE INSTRUCTIONS FOR EXISTING CUSTOMERS:
----------------------------------------------------------------------
1. Do not uninstall the old version.
2. Run "MINT-FASHION-POS-Setup.exe" to overwrite application binaries.
3. All existing business records, products, sales, and accounts remain intact.
======================================================================
`;

  fs.writeFileSync(releaseNotesPath, releaseNotesContent, 'utf8');
  console.log(`✓ Release notes generated at ${releaseNotesPath}`);

  // 8. Run build verification
  console.log('\nRunning build verification check...');
  execSync('node scripts/verify-build.js', { cwd: rootDir, stdio: 'inherit' });

  console.log('\n====================================================');
  console.log(` SUCCESS! Installer created: customer-release/${targetInstallerName}`);
  console.log('====================================================\n');
} catch (error) {
  console.error('\n✗ Packaging failed:', error.message);
  process.exit(1);
}
